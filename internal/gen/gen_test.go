// TestRunMatchesCommittedRegistry regenerates the registry from the real model
// definitions into a temporary file. The result must be byte-identical to the
// committed registry/models_gen.go: a difference means the models, the
// generator or the committed file changed without "make generate".
func TestRunMatchesCommittedRegistry(t *testing.T) {
	root := projectRoot()
	// The output directory does not exist yet: run must create it.
	outFile := filepath.Join(t.TempDir(), "nested", "registry", "models_gen.go")

	var stdout bytes.Buffer
	if err := run(filepath.Join(root, "models"), outFile, &stdout); err != nil {
		t.Fatalf("run: %v", err)
	}
	got, err := os.ReadFile(outFile)
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile(filepath.Join(root, "registry", "models_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("regenerated registry differs from the committed registry/models_gen.go (run \"make generate\"); first difference at %s",
			firstDiff(got, want))
	}

	models, err := schema.ParseDir(filepath.Join(root, "models"))
	if err != nil {
		t.Fatal(err)
	}
	wantMsg := fmt.Sprintf("gen: wrote %s (%d models, %d bytes)\n", outFile, len(models), len(got))
	if stdout.String() != wantMsg {
		t.Errorf("stdout = %q, want %q", stdout.String(), wantMsg)
	}
	if n := bytes.Count(got, []byte("\tRegister(&ModelMeta{\n")); n != len(models) {
		t.Errorf("%d Register calls for %d models", n, len(models))
	}
	if info, err := os.Stat(outFile); err != nil || info.Mode().Perm()&0o600 != 0o600 {
		t.Errorf("output file mode = %v, %v", info.Mode(), err)
	}
}

