func TestGenerateRejectsUnformattableSource(t *testing.T) {
	// goStr does not escape control characters, so a NUL in a name ends up
	// raw in the source, which gofmt refuses.
	src, err := generate([]schema.ModelDef{{ID: 1, Group: schema.GroupDef{Name: "a\x00b"}}})
	if err == nil {
		t.Fatalf("no error; generated %q", src)
	}
	if src != nil {
		t.Errorf("source = %q, want nil alongside an error", src)
	}
}

// compact strips the indentation-free output of writeModel and writeGroup
// down to one space-separated line, so that fragments can be matched.
func compact(src string) string {
	return strings.Join(strings.Fields(src), " ")
}

func TestWriteModelFraming(t *testing.T) {
	var buf bytes.Buffer
	writeModel(&buf, schema.ModelDef{ID: 5, Group: schema.GroupDef{
		Name: "m", Desc: "About m",
		// A count on the top-level group is ignored: it occurs once.
		Count:  schema.RawCount{StringVal: "N", IsString: true, IsSet: true},
		Points: []schema.PointDef{{Name: "ID", Type: "uint16", Size: 1}},
	}})
	out := buf.String()
	if !strings.HasPrefix(out, "\tRegister(&ModelMeta{\n\t\tID:    5,\n\t\tName:  \"m\",\n\t\tLabel: \"m\",\n\t\tDesc:  \"About m\",\n\t\tGroup: &GroupMeta{\n") ||
		!strings.HasSuffix(out, "},\n\t})\n") {
		t.Errorf("unexpected framing:\n%s", out)
	}
	want := `Group: &GroupMeta{ Name: "m", Desc: "About m", Type: "group", Count: 1, Length: 1, Points: []PointMeta{ ` +
		`{Name: "ID", Label: "", Desc: "", Type: "uint16", Size: 1, Offset: 0, Access: "R"}, }, }, })`
	if got := compact(out); !strings.HasSuffix(got, want) {
		t.Errorf("model body = %s\nwant suffix %s", got, want)
	}
	if strings.Contains(out, "CountPoint") {
		t.Errorf("the top-level group must not get a count point:\n%s", out)
	}
}

// How a nested group's "count" ends up in the generated GroupMeta.
func TestWriteGroupNestedCounts(t *testing.T) {
	pt := []schema.PointDef{{Name: "P", Type: "uint16", Size: 1}}
	tests := []struct {
		name  string
		count schema.RawCount
		want  string
	}{
		{"absent count", schema.RawCount{}, "Count: 1,"},
		{"count 1", schema.RawCount{IntVal: 1, IsSet: true}, "Count: 1,"},
		{"count 0", schema.RawCount{IsSet: true}, "Count: 0,"},
		{"count 4", schema.RawCount{IntVal: 4, IsSet: true}, "Count: 4,"},
		{"count by point", schema.RawCount{StringVal: "NPt", IsString: true, IsSet: true}, `CountPoint: "NPt",`},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			var buf bytes.Buffer
			writeGroup(&buf, schema.GroupDef{Name: "top", Points: pt, Groups: []schema.GroupDef{
				{Name: "child", Count: tc.count, Points: pt},
			}}, 1, "")
			got := compact(buf.String())
			want := `{ Name: "top", Type: "group", Count: 1, Length: 1, Points: []PointMeta{ ` +
				`{Name: "P", Label: "", Desc: "", Type: "uint16", Size: 1, Offset: 0, Access: "R"}, }, ` +
				`Groups: []*GroupMeta{ { Name: "child", Type: "group", ` + tc.want + ` Length: 1, Points: []PointMeta{ ` +
				`{Name: "P", Label: "", Desc: "", Type: "uint16", Size: 1, Offset: 0, Access: "R"}, }, }, }, }`
			if got != want {
				t.Errorf("got  %s\nwant %s", got, want)
			}
			// A group has either a fixed count or a count point, never both.
			if strings.Count(got, "Count: ")+strings.Count(got, "CountPoint: ") != 2 {
				t.Errorf("expected exactly one count per group: %s", got)
			}
		})
	}
}

func TestWriteGroupArguments(t *testing.T) {
	var buf bytes.Buffer
	// The count arguments decide, not the group's own definition.
	writeGroup(&buf, schema.GroupDef{Name: "g", Type: "sync", Label: "G", Count: schema.RawCount{IntVal: 9, IsSet: true}}, 3, "")
	if got, want := compact(buf.String()), `{ Name: "g", Label: "G", Type: "sync", Count: 3, Length: 0, }`; got != want {
		t.Errorf("got  %s\nwant %s", got, want)
	}
	buf.Reset()
	// A count point takes the place of the fixed count.
	writeGroup(&buf, schema.GroupDef{Name: "g"}, 3, "N")
	if got, want := compact(buf.String()), `{ Name: "g", Type: "group", CountPoint: "N", Length: 0, }`; got != want {
		t.Errorf("got  %s\nwant %s", got, want)
	}
}

func TestWriteGroupOffsetsAndDefaults(t *testing.T) {
	var buf bytes.Buffer
	writeGroup(&buf, schema.GroupDef{Name: "grp", Label: "Grp", Points: []schema.PointDef{
		{Name: "A", Type: "uint16"},                // size 0 counts as 1
		{Name: "B", Type: "string", Size: 3},       // offset 1
		{Name: "C", Type: "uint64", Size: 4},       // offset 4
		{Name: "D", Type: "pad", Size: 1},          // offset 8
		{Name: "E", Type: "int16", Mandatory: "O"}, // "O" is not mandatory
	}, Groups: []schema.GroupDef{
		// Offsets start again at 0 in a nested group, and its registers do
		// not count towards the parent's length.
		{Name: "sub", Points: []schema.PointDef{{Name: "F", Type: "uint32", Size: 2}, {Name: "G", Type: "uint16"}}},
	}}, 1, "")
	out := buf.String()

	for _, want := range []string{
		"Name: \"grp\",\n", "Label: \"Grp\",\n", "Type: \"group\",\n", "Count: 1,\n", "Length: 10,\n",
		`{Name: "A", Label: "", Desc: "", Type: "uint16", Size: 1, Offset: 0, Access: "R"},`,
		`{Name: "B", Label: "", Desc: "", Type: "string", Size: 3, Offset: 1, Access: "R"},`,
		`{Name: "C", Label: "", Desc: "", Type: "uint64", Size: 4, Offset: 4, Access: "R"},`,
		`{Name: "D", Label: "", Desc: "", Type: "pad", Size: 1, Offset: 8, Access: "R"},`,
		`{Name: "E", Label: "", Desc: "", Type: "int16", Size: 1, Offset: 9, Access: "R"},`,
		"Name: \"sub\",\nType: \"group\",\nCount: 1,\nLength: 3,\n",
		`{Name: "F", Label: "", Desc: "", Type: "uint32", Size: 2, Offset: 0, Access: "R"},`,
		`{Name: "G", Label: "", Desc: "", Type: "uint16", Size: 1, Offset: 2, Access: "R"},`,
	} {
		if !strings.Contains(out, want) {
			t.Errorf("output lacks %q:\n%s", want, out)
		}
	}

	// A group without points or nested groups is still a valid literal.
	buf.Reset()
	writeGroup(&buf, schema.GroupDef{Name: "empty"}, 0, "")
	if want := "{\nName: \"empty\",\nType: \"group\",\nCount: 0,\nLength: 0,\n}"; buf.String() != want {
		t.Errorf("empty group = %q, want %q", buf.String(), want)
	}
}

