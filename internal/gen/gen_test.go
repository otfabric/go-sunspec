func TestGoStr(t *testing.T) {
	tests := map[string]string{
		"":                   `""`,
		"plain":              `"plain"`,
		`say "hi"`:           `"say \"hi\""`,
		`back\slash`:         `"back\\slash"`,
		"line1\nline2":       `"line1\nline2"`,
		"col1\tcol2":         `"col1\tcol2"`,
		`\"`:                 `"\\\""`,
		`already \n here`:    `"already \\n here"`,
		"unicode °C é":       `"unicode °C é"`,
		"\\\n\t\"":           `"\\\n\t\""`,
		"percent %d %s 100%": `"percent %d %s 100%"`,
	}
	for in, want := range tests {
		got := goStr(in)
		if got != want {
			t.Errorf("goStr(%q) = %s, want %s", in, got, want)
		}
		// Whatever goStr emits must read back as the original string.
		back, err := strconv.Unquote(got)
		if err != nil || back != in {
			t.Errorf("goStr(%q) = %s does not unquote to the input (got %q, %v)", in, got, back, err)
		}
	}
}

